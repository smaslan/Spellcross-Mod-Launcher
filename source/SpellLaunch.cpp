// get version info by its hash
int SpellLaunch::GetVer(size_t hash,GameVersion &ver)
{
    auto vid = std::ranges::find_if(c_ver_list, [hash](const GameVersion &item){return(item.exe_hash == hash);});
    if(vid == c_ver_list.end())
        return(1);
    ver = *vid;
    return(0);
}

